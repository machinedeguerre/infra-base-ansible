#!/usr/bin/env bash
set -euo pipefail

pushd "$(dirname "$0")" >/dev/null

# Hardcoded configuration
HOSTS=(
  "bitbucket.org"
  "codeberg.org"
  "github.com"
  "gitlab.com"
)

KEY_TYPES="ed25519,ecdsa,rsa"
TIMEOUT_SECONDS="5"

# Output path in this repository (relative to this script)
OUT_FILE="../roles/sshd/files/ssh_known_hosts.base"

require() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: Required command not found: $1" >&2
    exit 127
  }
}

main() {
  require ssh-keyscan
  require mkdir
  require date

  mkdir -p "$(dirname "$OUT_FILE")"

  tmp="$(mktemp)"
  trap 'rm -f "$tmp"' EXIT

  {
    echo "# Managed file - generated by infra.base.sshd ansible role: infra/base/scripts/generate_known_hosts.sh"
    echo "# Generated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")"
    echo "# Commit this file to the repository."
    echo ""
  } > "$tmp"

  # Collect keys
  for host in "${HOSTS[@]}"; do
    echo "# ${host}" >> "$tmp"

    # ssh-keyscan writes comments to stderr sometimes; we only keep actual key lines from stdout
    ssh-keyscan -T "$TIMEOUT_SECONDS" -t "$KEY_TYPES" "$host" 2>/dev/null \
      | awk 'NF && $1 !~ /^#/' \
      >> "$tmp"
du
    echo "" >> "$tmp"
  done

  # Normalize: remove empty lines at end, de-dup exact duplicate lines, keep stable order
  # - Keep header/comments as-is
  # - De-dup key lines (exact match)
  awk '
    BEGIN { in_header=1 }
    /^#/ { print; next }
    NF==0 { print; next }
    {
      if (!seen[$0]++) print
    }
  ' "$tmp" \
  | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' \
  > "$OUT_FILE"

  echo "Wrote: $OUT_FILE"
}

main "$@"

popd >/dev/null
