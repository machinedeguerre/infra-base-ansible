#!/usr/bin/env bash
set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "ERROR: Ansible inventory host name is required (argument to this script)" >&2
  exit 1
fi

INVENTORY_HOST_NAME="$1"

if ! host_exists_in_inventory "$INVENTORY_HOST_NAME"; then
  echo "ERROR: Host not found in inventory: $INVENTORY_HOST_NAME" >&2
  exit 1
fi

VAULT_FILE="$PROJECT_ROOT/inventory/host_vars/${INVENTORY_HOST_NAME}/hostkeys.vault.yml"
VAULT_DIR="$(dirname "$VAULT_FILE")"
mkdir -p "$VAULT_DIR"

# Supported host key types
KEY_TYPES=(
  "ed25519"
  "rsa"
  "ecdsa"
)

require() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: Required command not found: $1" >&2
    exit 127
  }
}

cleanup() {
  if [[ -n "${WORK_DIR:-}" && -d "${WORK_DIR:-}" ]]; then
    rm -rf "$WORK_DIR"
  fi
}

main() {
  require ssh-keygen
  require ansible-vault
  require mktemp
  require mkdir
  require sed

  WORK_DIR="$(mktemp -d)"
  trap cleanup EXIT

  mkdir -p "$(dirname "$VAULT_FILE")"

  tmp_plain="${WORK_DIR}/vault_plain.yml"

  {
    echo "# Generated by generate_sshd_hostkeys.sh"
    echo "# Do not store private key material outside vault."
    echo ""
    echo "# sshd_host_keys structure (ready to use directly)"
    echo "sshd_host_keys:"
  } > "$tmp_plain"

  for key_type in "${KEY_TYPES[@]}"; do
    key_basename="ssh_host_${key_type}_key"
    priv="${WORK_DIR}/${key_basename}"
    pub="${priv}.pub"

    echo "Generating SSH host key (${key_type})..."

    if [[ "$key_type" == "rsa" ]]; then
      ssh-keygen -t rsa -b 4096 -N "" -f "$priv" -C "ansible-managed-hostkey" >/dev/null
    else
      ssh-keygen -t "$key_type" -N "" -f "$priv" -C "ansible-managed-hostkey" >/dev/null
    fi

    # Read keys into variables
    priv_content=$(cat "$priv")
    pub_content=$(cat "$pub")

    {
      echo "  - type: ${key_type}"
      echo "    private: |"
      echo "$priv_content" | sed 's/^/      /'
      echo "    public: |"
      echo "$pub_content" | sed 's/^/      /'
    } >> "$tmp_plain"
  done


  echo "Encrypting vault file → $VAULT_FILE"

  ansible-vault encrypt \
    --output "$VAULT_FILE" \
    --encrypt-vault-id project \
    "$tmp_plain"

  echo "Vault file created successfully."
}

main