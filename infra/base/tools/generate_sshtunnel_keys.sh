#!/usr/bin/env bash
set -euo pipefail

# Generates SSH ed25519 keypair for SSH reverse tunnels
# Stores them in an Ansible Vault YAML file
# Prints the public key to stdout at the end

if [ "$#" -lt 1 ]; then
  echo "ERROR: Ansible inventory host name is required (argument to this script)" >&2
  exit 1
fi

INVENTORY_HOST_NAME="$1"

if ! host_exists_in_inventory "$INVENTORY_HOST_NAME"; then
  echo "ERROR: Host not found in inventory: $INVENTORY_HOST_NAME" >&2
  exit 1
fi

VAULT_FILE="$PROJECT_ROOT/inventory/host_vars/${INVENTORY_HOST_NAME}/sshtunnel.vault.yml"
VAULT_DIR="$(dirname "$VAULT_FILE")"
mkdir -p "$VAULT_DIR"

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: Missing required command: $1" >&2
    exit 1
  }
}

umask 077

require_cmd ssh-keygen
require_cmd ansible-vault
require_cmd mktemp

# --- Generate keys ---
WORK_DIR="$(mktemp -d)"
cleanup() {
  if [[ -n "${WORK_DIR:-}" && -d "${WORK_DIR:-}" ]]; then
    rm -rf "$WORK_DIR"
  fi
}
trap cleanup EXIT

PRIVATE_KEY_FILE="${WORK_DIR}/sshtunnel_ed25519"
PUBLIC_KEY_FILE="${PRIVATE_KEY_FILE}.pub"

echo "Generating SSH ed25519 keypair for reverse tunnels..."

ssh-keygen -t ed25519 -N "" -f "$PRIVATE_KEY_FILE" -C "ansible-managed-sshtunnel-${INVENTORY_HOST_NAME}" >/dev/null

# Read keys into variables
private_key=$(cat "$PRIVATE_KEY_FILE")
public_key=$(cat "$PUBLIC_KEY_FILE")

# --- Write temporary YAML ---
tmp_plain="$(mktemp)"
cleanup2() {
  shred -u "$tmp_plain" 2>/dev/null || rm -f "$tmp_plain"
}
trap cleanup2 EXIT

cat >"$tmp_plain" <<YAML
# SSH tunnel keys (vault-encrypted)
# Generated by generate_sshtunnel_keys.sh
# Do not store private key material outside vault.
sshtunnel_private_key: |
$(echo "$private_key" | sed 's/^/  /')
YAML

mkdir -p "$(dirname "$VAULT_FILE")"

ansible-vault encrypt "$tmp_plain" --encrypt-vault-id project --output "$VAULT_FILE"

echo "Vault written to: $VAULT_FILE"
echo
echo "Public key (add this to authorized_keys on remote server):"
echo "$public_key"
